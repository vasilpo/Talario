namespace Tygh\Addons\Abt_unitheme2\SmartyEngine\Filters\Post;
use Smarty\Filter\FilterInterface;
use Smarty\Template;
class ReplaceImageGallery implements FilterInterface
{
public function filter($code, Template $template)
{
if (strpos($code, 'js/tygh/product_image_gallery.js') !== false) {
$code = str_replace('js/tygh/product_image_gallery.js', 'js/addons/abt__unitheme2/product_image_gallery.js', $code);
}
return $code;
}
}
